#!/usr/bin/env python3
"""Generate/check the user API inventory from compiler-owned declaration products."""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def _slice(lines: list[str], origin) -> str:
    selected = lines[origin.start_line - 1:origin.end_line]
    if not selected:
        raise ValueError("compiler returned an empty declaration range")
    selected[-1] = selected[-1][:origin.end_column - 1]
    selected[0] = selected[0][origin.start_column - 1:]
    return "\n".join(selected).strip()


def _contract(relative: Path) -> str:
    name = relative.as_posix()
    if name.startswith("debug/"):
        return "stdlib-debug.md"
    if name.startswith("bus/"):
        return "standard-bus-library.md"
    if name.startswith("target/"):
        return "../docs/target-platform-architecture-description.md"
    for key, chapter in (
        ("secded", "stdlib-secded.md"), ("farrow", "stdlib-farrow.md"),
        ("rs_dvb", "stdlib-rs-dvb.md"), ("gf256", "stdlib-rs-dvb.md"),
        ("viterbi", "stdlib-viterbi.md"), ("fir_reload", "stdlib-reloadable-fir.md"),
        ("fir_fold", "stdlib-reloadable-fir.md"), ("fir_coefficients", "stdlib-reloadable-fir.md"),
        ("cordic", "stdlib-multirate-coding.md"), ("cic", "stdlib-multirate-coding.md"),
        ("halfband", "stdlib-multirate-coding.md"), ("polyphase", "stdlib-multirate-coding.md"),
        ("nco", "stdlib-multirate-coding.md"), ("scrambler", "stdlib-multirate-coding.md"),
        ("convolutional", "stdlib-multirate-coding.md"),
    ):
        if key in name:
            return chapter
    if name.startswith(("stream/", "dsp/")) or "crc" in name:
        return "stdlib-stream-dsp.md"
    return "stdlib-overview.md"


def _interface_signature(interface) -> str:
    """Present a parser-owned endpoint that has no editor source span."""
    if any(not isinstance(argument.value, (str, int)) for argument in interface.arguments):
        raise ValueError("interface catalog requires a source-spelled integer/type argument")
    arguments = ",".join(
        (f"{argument.name}=" if argument.name is not None else "") + str(argument.value)
        for argument in interface.arguments
    )
    specialization = f"<{arguments}>" if arguments else ""
    domain = f" @{interface.domain}" if interface.domain else ""
    return (f"interface {interface.name} : {interface.protocol}{specialization}"
            f".{interface.role}{domain}")


def api_markdown(root: Path) -> str:
    """Use the production parser and symbol spans, including declaration-only files.

    Source slicing presents spelling only. Eligibility/type checking remains the
    compiler's job; this tool neither infers signatures nor evaluates ZLang.
    """
    from zlang.parser import parse
    from zlang.ast.nodes import PortDecl
    from zlang.tooling_symbols import document_symbols
    output = ["# Standard library API inventory", "",
        "Generated by `tools/document_stdlib.py` from compiler declaration and symbol products.",
        "Do not edit signatures here. Edit the ordinary ZLang source and regenerate the catalog.", "",
        "Each import below names a source namespace, not a qualification claim. Generic parameters",
        "and `where` clauses are part of the signature; a caller must select a legal specialization.",
        "Ports and record fields retain their declared width, sign and scale expressions.",
        "Pure helpers have no clock, latency or buffered transactions. Stateful modules have only",
        "the clocks, reset and ready/valid ports listed; component chapters specify edge/II/stall",
        "and numerical behavior. Resource descriptions are capabilities, not physical timing evidence.", "",
        "Source availability, successful simulation, synthesis and formal proof are distinct.",
        "No universal proof for all generic specializations is implied by this inventory.",
        "See the linked component contract and [recipes](stdlib-recipes.md) for executable usage.", ""]
    count = 0
    paths = sorted((root / "stdlib").rglob("*.zhl"))
    for path in paths:
        relative = path.relative_to(root / "stdlib")
        source = path.read_text(encoding="utf-8")
        syntax = parse(source)  # Fail closed; editor symbol queries tolerate parse failures.
        modules = {module.name: module for module in (syntax, *syntax.submodules)}
        symbols = document_symbols(source)
        lines = source.splitlines()
        logical = "std." + ".".join(relative.with_suffix("").parts)
        output += [f"## `{logical}`", "", f"Import: `import {logical}`.", "",
                   f"[Component contracts]({_contract(relative)}) · [Source](../stdlib/{relative.as_posix()})", ""]
        if not symbols:
            output += ["Import-only namespace; its source imports the component declarations listed in this catalog.", ""]
        for symbol in symbols:
            count += 1
            text = _slice(lines, symbol.range)
            # The compiler already identified the declaration. Its body starts
            # at the opening brace; this presentation never interprets the body.
            signature = text.split("{", 1)[0].rstrip()
            details = []
            if symbol.kind == "module":
                # Grouped ports do not always have individual editor symbols.
                # Conversely a generic-parameter editor fallback can span the
                # entire body. Only parser-owned public declarations belong here.
                module = modules[symbol.name]
                for item in module.ordered_items:
                    declaration = item if isinstance(item, PortDecl) else (
                        item[-1] if isinstance(item, tuple) and item[0] in {"clock", "reset"} else None
                    )
                    if declaration is not None:
                        if declaration.origin is None:
                            raise ValueError("public port/clock/reset declaration has no source span")
                        details.append(_slice(lines, declaration.origin))
                details.extend(_interface_signature(interface)
                               for interface in module.aggregate_interfaces)
            else:
                details.extend(_slice(lines, child.range) for child in symbol.children)
            if symbol.kind in {"class", "object", "interface"}:
                # Resource/architecture/target declarations carry their API in
                # capability and binding clauses, not only a callable header.
                # Preserve that compiler-bounded declaration verbatim.
                signature, details = text, []
            prefix = []
            index = symbol.range.start_line - 2
            while index >= 0 and lines[index].lstrip().startswith("//"):
                prefix.insert(0, lines[index].lstrip()[2:].strip())
                index -= 1
            output += [f"### `{symbol.name}` — {symbol.kind}", ""]
            if prefix:
                output += [" ".join(prefix), ""]
            output += ["```text", signature, *details, "```", "",
                f"[Exact declaration](../stdlib/{relative.as_posix()}#L{symbol.range.start_line}) · "
                f"[Contract and restrictions]({_contract(relative)})", ""]
    output += [f"Inventory: {len(paths)} source namespaces; {count} top-level declarations.", ""]
    return "\n".join(output)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    sys.path.insert(0, str(root))
    expected = api_markdown(root)
    destination = root / "docs/stdlib-api.md"
    if args.check:
        if not destination.is_file() or destination.read_text(encoding="utf-8") != expected:
            print("stdlib API inventory is stale", file=sys.stderr)
            return 1
    else:
        destination.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
